/**
 * Writes PRIVACY.md and privacy-site/index.html from the in-app privacy
 * policy (i18n privacy.*, constants/app.ts), so the app, the repo and the
 * hosted page (https://moj-budzet-privacy.vercel.app/) say the same thing.
 *
 *   node scripts/privacy-page.js
 *
 * Then deploy privacy-site/ to the Vercel project.
 */
const fs = require("fs");
const path = require("path");

// Run from the project root (where app.json is).
const root = process.cwd();
if (!fs.existsSync(path.join(root, "app.json"))) throw new Error("Run this from the project root");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");

// Same order as SECTIONS in screens/PrivacyScreen.tsx.
const SECTIONS = ["data", "storage", "backups", "sharing", "suggestions", "reminders", "rights", "children", "changes"];
const LANGUAGES = [
  { code: "en", name: "Moj Budzet" },
  { code: "mk", name: "Мој Буџет" },
];

const email = /CONTACT_EMAIL = "([^"]*)"/.exec(read("constants/app.ts"))?.[1];
if (!email) throw new Error("CONTACT_EMAIL is empty in constants/app.ts");

const policies = LANGUAGES.map(({ code, name }) => {
  const p = JSON.parse(read(`i18n/${code}.json`)).privacy;
  for (const key of SECTIONS) if (!p.sections[key]) throw new Error(`privacy.sections.${key} missing in ${code}`);
  return { code, name, p };
});

// ─── PRIVACY.md ───────────────────────────────────────────────────────────────
const markdown = policies
  .map(({ name, p }) =>
    [
      `## ${name} · ${p.title}`,
      p.intro,
      ...SECTIONS.map((key) => `### ${p.sections[key].title}\n\n${p.sections[key].body}`),
      `### ${p.contactTitle}\n\n${p.developer} ${email}`,
      `_${p.updated}_`,
    ].join("\n\n")
  )
  .join("\n\n---\n\n");

fs.writeFileSync(
  path.join(root, "PRIVACY.md"),
  `# Moj Budzet / Мој Буџет\n\n<!-- Generated by scripts/privacy-page.js from the in-app policy (i18n privacy.*). Edit those, not this file. -->\n\n${markdown}\n`
);

// ─── privacy-site/index.html ──────────────────────────────────────────────────
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const article = ({ code, name, p }) => `  <article id="${code}" lang="${code}">
    <h1>${esc(name)}</h1>
    <p class="title">${esc(p.title)}</p>
    <p>${esc(p.intro)}</p>
${SECTIONS.map((key) => `    <h2>${esc(p.sections[key].title)}</h2>\n    <p>${esc(p.sections[key].body)}</p>`).join("\n")}
    <h2>${esc(p.contactTitle)}</h2>
    <p>${esc(p.developer)} <a href="mailto:${email}">${email}</a></p>
    <p class="updated">${esc(p.updated)}</p>
  </article>`;

const html = `<!doctype html>
<!-- Generated by scripts/privacy-page.js from the in-app policy. Edit i18n privacy.*, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Moj Budzet – Privacy Policy</title>
  <meta name="description" content="Privacy policy of Moj Budzet / Мој Буџет. Your data stays on your device.">
  <style>
    :root { color-scheme: light dark; --bg: #f2f2f7; --card: #fff; --text: #1c1c1e; --muted: #6c6c70; --accent: #007aff; --line: #d1d1d6; }
    @media (prefers-color-scheme: dark) { :root { --bg: #000; --card: #1c1c1e; --text: #f2f2f7; --muted: #98989f; --accent: #0a84ff; --line: #38383a; } }
    * { box-sizing: border-box; }
    body { margin: 0; background: var(--bg); color: var(--text); font: 17px/1.55 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; }
    main { max-width: 680px; margin: 0 auto; padding: 24px 16px 48px; }
    nav { display: flex; gap: 8px; justify-content: flex-end; margin-bottom: 16px; }
    nav a { color: var(--accent); text-decoration: none; padding: 6px 12px; border: 1px solid var(--line); border-radius: 999px; font-size: 15px; }
    article { background: var(--card); border-radius: 16px; padding: 24px 20px; margin-bottom: 24px; }
    h1 { font-size: 28px; line-height: 1.2; margin: 0; }
    .title { color: var(--muted); margin: 4px 0 20px; }
    h2 { font-size: 19px; margin: 24px 0 6px; }
    p { margin: 0 0 8px; }
    a { color: var(--accent); }
    .updated { color: var(--muted); font-size: 15px; margin-top: 24px; }
  </style>
</head>
<body>
<main>
  <nav><a href="#en">English</a><a href="#mk">Македонски</a></nav>
${policies.map(article).join("\n")}
</main>
</body>
</html>
`;

fs.mkdirSync(path.join(root, "privacy-site"), { recursive: true });
fs.writeFileSync(path.join(root, "privacy-site", "index.html"), html);
console.log("Wrote PRIVACY.md and privacy-site/index.html");
